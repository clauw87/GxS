##                                                                                                                          ##
##                                                                                                                          ##
## Note: the permuted heatmap p-values are only as accurate as the number of replicates, for example:                       ##
##        6 /  101 = 0.059 ; 95%CI = 0.02750813 - 0.12359110                                                                ##
##       51 / 1001 = 0.051 ; 95%CI = 0.03896177 - 0.06636973                                                                ##
##       36 / 1001 = 0.036 ; 95%CI = 0.02608937 - 0.04938667                                                                ##
##       Hence, 1000 permutations are sufficient to indicate pointwise significance                                         ##
##       and whether more permutations are desired to give a 95%CI which does not include 0.05.                             ##
##                                                                                                                          ##
##       10000 permutations are preferable, but would unnecessarily take too long (if there is no trend):                   ##
##       501/10001 = 0.050 ; 95%CI = 0.04598980 - 0.05454568                                                                ##
##       461/10001 = 0.046 ; 95%CI = 0.04215709 - 0.05038225                                                                ##
##                                                                                                                          ##
