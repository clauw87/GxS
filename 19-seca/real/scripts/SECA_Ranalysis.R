# 'source' a 'local' version of the "binom.confint" function to calculate the Wilson score confidence intervals:
binom.confintWILSON<-function (x, n, conf.level = 0.95, methods = "all", ...) 
{
    if ((length(x) != length(n))) {
        m <- cbind(x = x, n = n)
        x <- m[, "x"]
        n <- m[, "n"]
    }
    res <- NULL
    binom.methods <- c("wilson", "all")
    method <- pmatch(methods, binom.methods)
    if (all(is.na(method))) {
        methods <- paste(paste("\"", methods, "\"", sep = ""), 
            collapse = ", ")
        stop("method(s) ", methods, "\" not matched")
    }
    if (any(is.na(method))) {
        warning("method(s) ", methods[is.na(method)], " not matched")
        method <- methods[!is.na(method)]
    }
    method <- binom.methods[method]
    out <- x > n | x < 0
    if (any(out)) {
        warning("observations with more successes than trials detected and removed")
        x <- x[!out]
        n <- n[!out]
    }
    xn <- data.frame(x = x, n = n)
    all.methods <- any(method == "all")
    p <- x/n
    alpha <- 1 - conf.level
    alpha <- rep(alpha, length = length(p))
    alpha2 <- 0.5 * alpha
    z <- qnorm(1 - alpha2)
    z2 <- z * z
    res <- NULL
    if (any(method == "wilson") || all.methods) {
        p1 <- p + 0.5 * z2/n
        p2 <- z * sqrt((p * (1 - p) + 0.25 * z2/n)/n)
        p3 <- 1 + z2/n
        lcl <- (p1 - p2)/p3
        ucl <- (p1 + p2)/p3
        x1 <- x == 1
        x2 <- x == n - 1
        if (any(x1)) 
            lcl[x1] <- -log(1 - alpha[x1])/n[x1]
        if (any(x2)) 
            ucl[x2] <- 1 + log(1 - alpha[x2])/n[x2]
        res.wilson <- cbind(method = rep("wilson", NROW(x)), 
            xn, mean = p, lower = lcl, upper = ucl)
        res <- if (is.null(res)) 
            res.wilson
        else rbind(res, res.wilson)
    }
    attr(res, "conf.level") <- conf.level
    row.names(res) <- seq(nrow(res))
    res
