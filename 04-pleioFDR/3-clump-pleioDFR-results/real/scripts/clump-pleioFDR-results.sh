# Modules
#module load modulepath/noarch
module load PLINK/1.9b
module load Python/3.6.6-foss-2018b

# Config
INPUTS_LIST=$1
REFERENCE_FILE=$2
OUTPUTS_DIR_GRAL=$3

# Cluster Array
INPUT_FILE=$(cat "${INPUTS_LIST}" | sed -n ${SLURM_ARRAY_TASK_ID}p)

# Variables
CODE=$(echo ${INPUT_FILE} | cut -d' ' -f1)
ORIGINAL_RESULTS=$(echo ${INPUT_FILE} | cut -d' ' -f3)
MAT_FILE=$(echo ${INPUT_FILE} | cut -d' ' -f2)


# Creates output dir
OUTPUT_DIR=${OUTPUTS_DIR_GRAL}/${CODE}
mkdir -p ${OUTPUT_DIR}


# Transforms result.mat generated by pleioFDR into a csv file
python ./real/scripts/mat-to-csv.py \
       ${MAT_FILE} \
       ${OUTPUT_DIR}/myresult.csv \
       ${REFERENCE_FILE}


# Same but with library fun
python /gpfs42/projects/lab_anavarro/disease_pleiotropies/LifespanPleiotropies_2/software/python_convert/sumstats.py \
    mat-to-csv \
    --force \
    --mat ${MAT_FILE} \
    --ref ${REFERENCE_FILE} \
    --out ${OUTPUT_DIR}/result.csv


# Clumps pleioFDR results
# supposedly the default parameters are FUMA 2 steps clumping
#     --ld-window-r2

python /gpfs42/projects/lab_anavarro/disease_pleiotropies/LifespanPleiotropies_2/software/python_convert/sumstats.py clump \
	--clump-field FDR \
        --ld-window-kb 250 \ # default =10000 "Window size in KB to search for clumped SNPs. "
        --loci-merge \ # default =250
	--force  \
	--sumstats ${OUTPUT_DIR}/result.csv \
	--bfile-chr /gpfs42/projects/lab_anavarro/disease_pleiotropies/LifespanPleiotropies_2/data/ref_1kG_phase3_EUR/chr@ \
        --exclude-ranges 6:25119106-33854733 8:7200000-12500000 \
	--clump-p1 0.05 \
	--out ${OUTPUT_DIR}/result.clump


# Merges clumped results with original ones to retrieve zscore values
cat ${OUTPUT_DIR}/result.clump.indep.csv \
  | tail -n +2 \
  | cut -f3 \
  > ${OUTPUT_DIR}/clumped.snps
cat ${ORIGINAL_RESULTS} \
  | head -1 \
  > ${OUTPUT_DIR}/zscore-result.clumped
cat ${ORIGINAL_RESULTS} \
  | grep -w -f ${OUTPUT_DIR}/clumped.snps \
  >> ${OUTPUT_DIR}/zscore-result.clumped
